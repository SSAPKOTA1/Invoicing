"""PostgreSQL access layer: placeholders, rows, transactions, savepoints, errors."""

from __future__ import annotations

import pytest

from supplier_app.database.errors import INTEGRITY_ERRORS
from supplier_app.database.pg import PgDatabase, translate_sql
from supplier_app.errors import DatabaseError


def test_sql_translation() -> None:
    assert translate_sql("SELECT * FROM t WHERE a=? AND b LIKE ?") == "SELECT * FROM t WHERE a=%s AND b ILIKE %s"
    assert translate_sql("SELECT '?' , '100%'") == "SELECT '?' , '100%%'"  # placeholders inside literals stay, % is doubled
    assert translate_sql("WHERE x LIKE '%a_' ESCAPE '\\'") == "WHERE x ILIKE '%%a_' ESCAPE '\\'"


@pytest.fixture()
def db(pg_dsn):
    d = PgDatabase(pg_dsn).connect()
    d.execute("CREATE TABLE t(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, x TEXT UNIQUE, n BIGINT)")
    yield d
    d.close()


def test_rows_scalars_insert_and_types(db) -> None:
    first = db.insert("INSERT INTO t(x, n) VALUES (?,?)", ("a", 5))
    second = db.insert("INSERT INTO t(x, n) VALUES (?,?)", ("b", 7))
    assert (first, second) == (1, 2)
    row = db.query_one("SELECT id, x, n FROM t WHERE x=?", ("b",))
    assert row["x"] == "b" and row[0] == 2 and row.keys() == ["id", "x", "n"]
    assert db.scalar("SELECT SUM(n) FROM t") == 12 and isinstance(db.scalar("SELECT SUM(n) FROM t"), int)  # NUMERIC -> int
    assert db.scalar("SELECT n FROM t WHERE x=?", ("zzz",), default=-1) == -1
    assert [r["x"] for r in db.query_all("SELECT x FROM t WHERE x LIKE ? ORDER BY x", ("A%",))] == ["a"]  # case-insensitive
    db.execute("UPDATE t SET n=? WHERE x=?", (True, "a"))  # bools are stored as 0/1
    assert db.scalar("SELECT n FROM t WHERE x='a'") == 1
    assert db.schema_version() >= 1 and db.integrity_ok()


def test_nested_transactions_savepoints_and_rollback(db) -> None:
    with db.transaction():
        db.execute("INSERT INTO t(x) VALUES ('outer')")
        with pytest.raises(RuntimeError), db.transaction():
            db.execute("INSERT INTO t(x) VALUES ('inner')")
            raise RuntimeError("boom")
        assert db.scalar("SELECT COUNT(*) FROM t") == 1  # only the inner part was undone
        assert db.in_transaction
    assert not db.in_transaction and db.scalar("SELECT COUNT(*) FROM t") == 1
    with pytest.raises(RuntimeError), db.transaction():
        db.execute("INSERT INTO t(x) VALUES ('weg')")
        raise RuntimeError("boom")
    assert db.scalar("SELECT COUNT(*) FROM t") == 1


def test_a_rejected_statement_does_not_abort_the_transaction(db) -> None:
    db.execute("INSERT INTO t(x) VALUES ('dup')")
    with db.transaction():
        db.execute("INSERT INTO t(x) VALUES ('ok1')")
        with pytest.raises(INTEGRITY_ERRORS):
            db.execute("INSERT INTO t(x) VALUES ('dup')")  # statement-level rollback, the booking goes on
        db.execute("INSERT INTO t(x) VALUES ('ok2')")
    assert db.scalar("SELECT COUNT(*) FROM t") == 3


def test_errors_are_friendly(db, pg_dsn) -> None:
    with pytest.raises(DatabaseError, match="Datenbankfehler"):
        db.execute("SELECT * FROM gibt_es_nicht")
    db.read_only = True
    with pytest.raises(DatabaseError, match="Lesen"):
        db.execute("INSERT INTO t(x) VALUES ('x')")
    assert db.scalar("SELECT 1") == 1
    db.read_only = False
    with pytest.raises(DatabaseError, match="Server"):
        PgDatabase("host=127.0.0.1 port=1 dbname=x user=y connect_timeout=2").connect()
    other = PgDatabase(pg_dsn).connect()
    try:
        with db.transaction():  # a colleague holds the write lock: the wait ends with a clear message
            other.execute("SET lock_timeout = 300")
            with pytest.raises(DatabaseError, match="belegt"), other.transaction():
                pass
    finally:
        other.close()
